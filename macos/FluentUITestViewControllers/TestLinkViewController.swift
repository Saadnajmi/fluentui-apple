        let dropdown = NSPopUpButton()
        dropdown.pullsDown = true
		dropdown.contentTintColor = .systemGreen
        
        let cell = dropdown.cell as! NSPopUpButtonCell
        cell.arrowPosition = .arrowAtBottom
        dropdown.select(nil)
		
        let image = NSImage(named: NSImage.iconViewTemplateName)!
        image.size = CGSize(width: 15, height: 15)
        dropdown.image = image
		
		dropdown.bezelStyle = .recessed
